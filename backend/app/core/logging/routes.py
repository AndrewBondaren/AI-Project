def route_for(logger_name: str) -> LogRoute:
    name = logger_name
    while name:
        route = _BY_NAME.get(name)
        if route is not None and (name == logger_name or route.consumer in _NAMESPACES):
            return route
        name = name.rpartition(".")[0]
    raise UnknownLogConsumerError(logger_name)
