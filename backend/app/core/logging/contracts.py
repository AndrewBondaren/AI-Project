class LogRoute(BaseModel):
    model_config = ConfigDict(frozen=True, strict=True, extra="forbid", revalidate_instances="always")
    consumer: LogConsumer
    sink: LogSink
    server_enabled: StrictBool
    generation_enabled: StrictBool


class UnknownLogConsumerError(ValueError):
    def __init__(self, logger_name: str) -> None:
        self.logger_name = logger_name
        super().__init__(f"Unregistered logger: {logger_name!r}")
