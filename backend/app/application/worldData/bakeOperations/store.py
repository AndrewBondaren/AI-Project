import sqlite3
from collections.abc import Callable
from typing import Protocol

from app.dataModel.world.bakeOperation.admission import BakeAdmission
from app.dataModel.world.bakeOperation.record import BakeOwner, BakeRecord, BakeResult, DeliveryStatus, RolledBack, Waiter
from app.dataModel.world.bakeOperation.request import BakeRequest

type Evidence = Callable[[sqlite3.Connection, BakeRecord], BakeResult | RolledBack | None]


class WaiterStore(Protocol):
    def status(self, operation: str, waiter: Waiter) -> DeliveryStatus | None: ...
    def finish(self, operation: str, waiter: Waiter, status: DeliveryStatus) -> None: ...


class BakeStore(Protocol):
    @property
    def waiters(self) -> WaiterStore: ...
    @property
    def lease_seconds(self) -> int: ...
    def admit(self, request: BakeRequest, waiter: Waiter) -> BakeAdmission: ...
    def read(self, operation: str) -> BakeRecord: ...
    def cancel_preparation(self, operation: str) -> bool: ...
    def recover(self) -> BakeOwner | None: ...
    def heartbeat(self, token: BakeOwner) -> None: ...
    def begin(self, token: BakeOwner) -> BakeRecord: ...
    def publishing(self, token: BakeOwner, publication: str) -> None: ...
    def uncertain(self, token: BakeOwner) -> None: ...
    def publication(self, token: BakeOwner, evidence: Evidence) -> None: ...
    def prepared_terminal(self, token: BakeOwner, result: BakeResult | None, error: str | None) -> None: ...
